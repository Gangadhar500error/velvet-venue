function buildJourney(verified: boolean, hasBooking: boolean, hasReview: boolean): JourneyStep[] {
  return [
    { key: "registered", label: "Registered", status: "completed", date: "Jan 12, 2024" },
    {
      key: "verified",
      label: "Verified",
      status: verified ? "completed" : "current",
      date: verified ? "Jan 12, 2024" : undefined,
    },
    {
      key: "first_booking",
      label: "First Booking",
      status: hasBooking ? "completed" : verified ? "current" : "pending",
      date: hasBooking ? "Feb 03, 2024" : undefined,
    },
    {
      key: "upcoming",
      label: "Upcoming Event",
      status: hasBooking ? "completed" : "pending",
      date: hasBooking ? "Aug 12, 2026" : undefined,
    },
    {
      key: "completed",
      label: "Completed Event",
      status: hasBooking ? (hasReview ? "completed" : "current") : "pending",
      date: hasBooking ? "Jul 28, 2026" : undefined,
    },
    {
      key: "review",
      label: "Review Submitted",
      status: hasReview ? "completed" : hasBooking ? "current" : "pending",
      date: hasReview ? "Jul 29, 2026" : undefined,
    },
  ];
}

