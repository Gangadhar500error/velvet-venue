function enrich(
  base: Omit<
    Customer,
    | "journey"
    | "recentBookings"
    | "recentInvoices"
    | "recentTransactions"
    | "recentReviews"
    | "activities"
    | "emailVerified"
    | "mobileVerified"
    | "communicationPreference"
    | "upcomingBookings"
    | "completedBookings"
    | "cancelledBookings"
    | "averageBooking"
    | "totalPaid"
    | "pendingPayments"
    | "refundedPayments"
    | "favoriteEventType"
    | "averageRating"
    | "country"
    | "createdBy"
    | "createdAt"
    | "updatedBy"
    | "updatedAt"
    | "version"
    | "gender"
    | "dob"
  > &
    Partial<Customer>
): Customer {
  const verified = base.verification === "verified";
  const hasBooking = (base.bookings || 0) > 0;
  const hasReview = (base.reviews || 0) > 0;

  return {
    country: "India",
    addressLine1: "",
    addressLine2: "",
    state: "",
    zipCode: "",
    gender: "prefer_not_to_say",
    dob: "",
    emailVerified: verified,
    mobileVerified: verified,
    communicationPreference: "email",
    upcomingBookings: base.upcomingBookings ?? 0,
    completedBookings: base.completedBookings ?? 0,
    cancelledBookings: base.cancelledBookings ?? 0,
    averageBooking: base.averageBooking ?? 0,
    totalPaid: base.totalPaid ?? 0,
    pendingPayments: base.pendingPayments ?? 0,
    refundedPayments: base.refundedPayments ?? 0,
    favoriteEventType: base.favoriteEventType ?? "—",
    averageRating: hasReview ? base.averageRating ?? 4.6 : 0,
    createdBy: "System",
    createdAt: base.registrationDate,
    updatedBy: "Admin User",
    updatedAt: base.lastLogin,
    version: "v1.0",
    journey: buildJourney(verified, hasBooking, hasReview),
    recentBookings: base.recentBookings ?? [],
    recentInvoices: base.recentInvoices ?? [],
    recentTransactions: base.recentTransactions ?? [],
    recentReviews: hasReview ? sampleReviews : [],
    activities: sampleActivities,
    ...base,
    bookings: base.bookings ?? 0,
    totalSpend: base.totalSpend ?? 0,
  } as Customer;
}

